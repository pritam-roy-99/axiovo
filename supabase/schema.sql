-- ResearchLens optional Supabase social backend
-- Run in Supabase SQL Editor after creating a project.
-- Every public-facing table has row-level security (RLS).
-- Use the public/publishable browser key, NEVER the service_role secret.

create table if not exists public.research_profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default 'Researcher' check (char_length(display_name) between 1 and 100),
 affiliation text not null default '' check (char_length(affiliation)<=200),
 about text not null default '' check (char_length(about)<=2000),
 orcid text not null default '' check (char_length(orcid)<=90),
 interests text[] not null default '{}'::text[],
 is_public boolean not null default false,
 updated_at timestamptz not null default now()
);
alter table public.research_profiles enable row level security;
drop policy if exists "research_profiles_public_or_own" on public.research_profiles;
create policy "research_profiles_public_or_own" on public.research_profiles for select to authenticated, anon using (is_public or auth.uid()=user_id);
drop policy if exists "research_profiles_insert_own" on public.research_profiles;
create policy "research_profiles_insert_own" on public.research_profiles for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "research_profiles_update_own" on public.research_profiles;
create policy "research_profiles_update_own" on public.research_profiles for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "research_profiles_delete_own" on public.research_profiles;
create policy "research_profiles_delete_own" on public.research_profiles for delete to authenticated using (auth.uid()=user_id);

create table if not exists public.paper_votes (
 paper_id text not null check (char_length(paper_id) between 5 and 50),
 user_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key (paper_id,user_id)
);
alter table public.paper_votes enable row level security;
drop policy if exists "paper_votes_public_read" on public.paper_votes;
create policy "paper_votes_public_read" on public.paper_votes for select to anon,authenticated using (true);
drop policy if exists "paper_votes_insert_own" on public.paper_votes;
create policy "paper_votes_insert_own" on public.paper_votes for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "paper_votes_delete_own" on public.paper_votes;
create policy "paper_votes_delete_own" on public.paper_votes for delete to authenticated using (auth.uid()=user_id);

create table if not exists public.paper_comments (
 id bigint generated by default as identity primary key,
 paper_id text not null check (char_length(paper_id) between 5 and 50),
 user_id uuid not null references auth.users(id) on delete cascade,
 body text not null check (char_length(body) between 3 and 4000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists paper_comments_paper_time on public.paper_comments(paper_id,created_at desc);
alter table public.paper_comments enable row level security;
drop policy if exists "paper_comments_public_read" on public.paper_comments;
create policy "paper_comments_public_read" on public.paper_comments for select to anon,authenticated using (true);
drop policy if exists "paper_comments_insert_own" on public.paper_comments;
create policy "paper_comments_insert_own" on public.paper_comments for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "paper_comments_update_own" on public.paper_comments;
create policy "paper_comments_update_own" on public.paper_comments for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);
drop policy if exists "paper_comments_delete_own" on public.paper_comments;
create policy "paper_comments_delete_own" on public.paper_comments for delete to authenticated using (auth.uid()=user_id);

-- Optional follow graph for researcher profiles. A followed user's profile
-- is only publicly readable when the owner has opted in.
create table if not exists public.profile_follows (
 follower_id uuid not null references auth.users(id) on delete cascade,
 followed_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key (follower_id,followed_id),
 check (follower_id <> followed_id)
);
alter table public.profile_follows enable row level security;
drop policy if exists "profile_follows_read" on public.profile_follows;
create policy "profile_follows_read" on public.profile_follows for select to authenticated using (follower_id=auth.uid() or followed_id=auth.uid());
drop policy if exists "profile_follows_insert" on public.profile_follows;
create policy "profile_follows_insert" on public.profile_follows for insert to authenticated with check (follower_id=auth.uid());
drop policy if exists "profile_follows_delete" on public.profile_follows;
create policy "profile_follows_delete" on public.profile_follows for delete to authenticated using (follower_id=auth.uid());

