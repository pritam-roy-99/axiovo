const assert=require("node:assert/strict");
const e=require("../docs/citation-evidence.js");
const arxiv={source:"arxiv",id:"2601.12345v2",title:"Quantum contextuality"};
const bio={source:"biorxiv",id:"10.1101/2026.01.01.000001",doi:"https://doi.org/10.1101/2026.01.01.000001",title:"Cell biology"};
const chem={source:"chemrxiv",doi:"10.26434/chemrxiv-2026-abc",title:"Nanomaterials"};
const crypto={source:"eprint",recordId:"2025/001",title:"Proof systems for quantum cryptography"};
const ssId="649def34f8be52c8b66281af98ae884c09aef38b";
assert.equal(e.identity(arxiv).arxiv,"2601.12345");
assert.equal(e.identity(bio).doi,"10.1101/2026.01.01.000001");
assert.equal(e.identity(crypto).eprint,"2025/001");
assert.equal(e.identity(crypto).arxiv,"");
assert(e.directories(arxiv).some(x=>x.name==="arXiv record"&&x.url.endsWith("/2601.12345")));
assert(e.directories(bio).some(x=>x.name==="DOI record"));
assert(e.directories(crypto).some(x=>x.name==="IACR ePrint record"&&x.url==="https://eprint.iacr.org/2025/001"));
assert(!e.directories(crypto).some(x=>x.name==="INSPIRE-HEP"));
assert(!e.directories(crypto).some(x=>x.name==="DOI record"));
assert(e.directories(arxiv).some(x=>x.name==="Search Google Scholar (unverified)"));
const crossref={crossref:{message:{DOI:"10.1101/2026.01.01.000001","is-referenced-by-count":12}}};
assert.deepEqual(e.resultsFor(bio,crossref).map(x=>x.count),[12]);
assert.equal(e.resultsFor(bio,crossref)[0].url,"https://doi.org/10.1101%2F2026.01.01.000001");
assert.deepEqual(e.resultsFor(bio,{crossref:{message:{DOI:"10.1101/wrong","is-referenced-by-count":999}}}),[]);
for(const invalid of [null,-1,"4",1.2])
 assert.deepEqual(e.resultsFor(bio,{crossref:{message:{DOI:bio.doi,"is-referenced-by-count":invalid}}}),[]);
assert.deepEqual(e.resultsFor(bio,{openalex:{id:"https://openalex.org/W12345",doi:"https://doi.org/10.1101/2026.01.01.000001",cited_by_count:24}}).map(x=>x.count),[24]);
assert.deepEqual(e.resultsFor(bio,{openalex:{id:"https://openalex.org/W12345",doi:"https://doi.org/10.1234/wrong",cited_by_count:2000,locations:[{doi:"https://doi.org/10.1101/2026.01.01.000001"}]}}),[]);
assert.deepEqual(e.resultsFor(bio,{openalex:{doi:bio.doi,cited_by_count:300}}),[]); // no verified direct OpenAlex ID
const sem={paperId:ssId,citationCount:900,externalIds:{ArXiv:"2601.12345"}};
assert.deepEqual(e.resultsFor(arxiv,{semantic:sem}).map(x=>x.count),[900]);
assert.equal(e.resultsFor(arxiv,{semantic:sem})[0].url,"https://www.semanticscholar.org/paper/"+ssId);
assert.deepEqual(e.resultsFor(arxiv,{semantic:{...sem,externalIds:{ArXiv:"2601.12346"}}}),[]);
assert.deepEqual(e.resultsFor(arxiv,{semantic:{...sem,paperId:"wrong"}}),[]);
const hit={id:88211,metadata:{arxiv_eprints:[{value:"2601.12345"}],citation_count:15}};
assert.deepEqual(e.resultsFor(arxiv,{inspire:{hits:{hits:[hit]}}}).map(x=>x.count),[15]);
assert.equal(e.resultsFor(arxiv,{inspire:{hits:{hits:[hit]}}})[0].url,"https://inspirehep.net/literature/88211");
assert.deepEqual(e.resultsFor(arxiv,{inspire:{hits:{hits:[{...hit,metadata:{...hit.metadata,arxiv_eprints:[{value:"2601.12346"}]}}]}}}),[]);
assert.deepEqual(e.resultsFor(crypto,{semantic:sem,openalex:{id:"https://openalex.org/W123",cited_by_count:700}}),[]);
