"use strict";
const assert=require("node:assert/strict");
const Fields=require("../docs/research-fields.js");
const Custom=require("../docs/custom-taxonomy.js");
function memory(){
 const data=new Map();
 return {getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v),data};
}
const db=memory();
Custom.load(db);
assert.equal(Fields.FIELDS.statmech.topics.includes("Nonequilibrium statistical mechanics"),true);
const a=Custom.addArea("statmech","Driven open systems",db);
assert.equal(a.ok,true);
assert(Fields.FIELDS.statmech.topics.includes("Driven open systems"));
const b=Custom.addInterest("statmech","Driven open systems","Fluctuations in active engines",db);
assert.equal(b.ok,true);
assert(Fields.fieldTopics("statmech","Driven open systems").includes("Fluctuations in active engines"));
assert.equal(Custom.addArea("statmech","DRIVEN OPEN SYSTEMS",db).restored,true);
assert.equal(Fields.FIELDS.statmech.topics.filter(t=>t==="Driven open systems").length,1);
assert.equal(Fields.FIELDS.condmat.topics.includes("Driven open systems"),false);
assert.equal(Custom.removeInterest("statmech","Driven open systems","Fluctuations in active engines",db),true);
assert.equal(Fields.fieldTopics("statmech","Driven open systems").includes("Fluctuations in active engines"),false);
assert.equal(Custom.removeArea("statmech","Driven open systems",db),true);
assert.equal(Fields.FIELDS.statmech.topics.includes("Driven open systems"),false);
assert.equal(Custom.removeArea("condmat","Superconductivity",db),true);
assert.equal(Fields.FIELDS.condmat.topics.includes("Superconductivity"),false);
assert.equal(Fields.FIELDS.statmech.topics.includes("Phase transitions and critical phenomena"),true);
Custom.load(db);
assert.equal(Fields.FIELDS.condmat.topics.includes("Superconductivity"),false);
assert.equal(Custom.addArea("condmat","superconductivity",db).restored,true);
assert.equal(Fields.FIELDS.condmat.topics.includes("Superconductivity"),true);
const topic="Topological phases of matter";
const interest="Topological order and anyons";
assert.equal(Custom.removeInterest("condmat",topic,interest,db),true);
assert.equal(Fields.fieldTopics("condmat",topic).includes(interest),false);
assert.equal(Custom.addInterest("condmat",topic,interest,db).restored,true);
assert.equal(Fields.fieldTopics("condmat",topic).includes(interest),true);
assert.equal(Custom.addArea("condmat","x",db).ok,false);
assert.equal(Custom.addInterest("condmat",topic,"x",db).ok,false);
assert.equal(Custom.restore("condmat",db),true);
assert.equal(Fields.FIELDS.condmat.topics.length,12);
assert.equal(Custom.restore("statmech",db),true);
assert.equal(Fields.FIELDS.statmech.topics.length,12);
assert.equal(Fields.fieldTopics("statmech","Nonequilibrium statistical mechanics").length,4);
assert.equal(Fields.FIELDS.quantum.topics.length,10);
console.log("Personal custom taxonomy add/delete/restore, persistence and field isolation passed.");
